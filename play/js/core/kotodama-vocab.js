  /**
   * フェーズに対応する語彙を返す。
   * エントリが無ければ直近下位フェーズ → default にフォールバック。
   * @param {string} type   ことだまID (kyokan/nori/fukagori/change/nomiyo/renraku/kanshi)
   * @param {number} phase  現在のフェーズ (0-4)
   * @returns {{label:string, sub:string, lines:string[]}|null}
   */
  function get(type, phase) {
    const table = VOCAB[type];
    if (!table) return null;
    for (let p = phase; p >= 0; p--) {
      if (table[p]) return table[p];
    }
    return table.default || null;
  }

  /**
   * 発動時の自分のセリフを lines からランダムで1本選ぶ。
   * topicId に固有の line があればそれを優先（S6: 相槌の文脈化）。
   * セリフが無い（静観・語彙未定義）場合は null。
   * @param {string} type
   * @param {number} phase
   * @param {string} [topicId]  現在のシチュエーション/スレッドの話題ID
   * @returns {string|null}
   */
  function pickLine(type, phase, topicId) {
    const topical = topicId && TOPIC_LINES[topicId] && TOPIC_LINES[topicId][type];
    if (topical && topical.length > 0) {
      return topical[Math.floor(Math.random() * topical.length)];
    }
    const v = get(type, phase);
    if (!v || !v.lines || v.lines.length === 0) return null;
    return v.lines[Math.floor(Math.random() * v.lines.length)];
  }

  // ── public API ───────────────────────────────────
